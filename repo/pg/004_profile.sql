-- Perfil de usuario: display_name, avatar, bio + listas de rutas + tracks planeadas
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS display_name text,
  ADD COLUMN IF NOT EXISTS avatar_key   text,
  ADD COLUMN IF NOT EXISTS bio          text,
  ADD COLUMN IF NOT EXISTS updated_at   timestamptz;

CREATE TABLE IF NOT EXISTS user_lists (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name        text NOT NULL,
  description text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS user_list_tracks (
  list_id     integer NOT NULL REFERENCES user_lists(id) ON DELETE CASCADE,
  track_id    integer NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
  position    integer NOT NULL DEFAULT 0,
  added_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (list_id, track_id)
);

CREATE INDEX IF NOT EXISTS idx_user_lists_owner ON user_lists (owner_id);
CREATE INDEX IF NOT EXISTS idx_user_list_tracks_list ON user_list_tracks (list_id);
CREATE INDEX IF NOT EXISTS idx_user_list_tracks_track ON user_list_tracks (track_id);

ALTER TABLE tracks
  ADD COLUMN IF NOT EXISTS planned boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_tracks_planned ON tracks (planned) WHERE planned = true;
