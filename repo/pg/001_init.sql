-- Esquema inicial de PostgreSQL, equivalente al de SQLite (scripts/db.js) para que ambos motores
-- devuelvan exactamente lo mismo. Diferencias deliberadas:
--   · raw_points / clean_points → una geometría por track (geom / geom_clean) + array de altitudes
--     (ele / ele_clean), porque PostGIS no admite Z nula y hay puntos sin altitud.
--   · Los campos JSON siguen como texto para conservar la forma de las filas.
CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE tracks (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             text NOT NULL,
  file             text UNIQUE NOT NULL,
  zone             text,
  date             text,
  distance         double precision,
  elevation_gain   integer,
  elevation_loss   integer,
  min_elevation    integer,
  max_elevation    integer,
  sw_lat double precision, sw_lon double precision, ne_lat double precision, ne_lon double precision,
  center_lat double precision, center_lon double precision,
  raw_count        integer NOT NULL DEFAULT 0,
  clean_count      integer,
  cleaned          integer NOT NULL DEFAULT 0,
  color            text,
  imported_at      timestamptz NOT NULL DEFAULT now(),
  cleaned_at       timestamptz,
  activity         text,
  province         text,
  ccaa             text,
  sierra           text,
  notes            text,
  url              text,
  road_types       text,
  surface_types    text,
  road_types_at    text,
  moving_time      integer,
  stopped_time     integer,
  tags             text,
  ibp_bicycle      double precision,
  ibp_hiking       double precision,
  ibp_running      double precision,
  is_recent_import integer DEFAULT 0,
  circular         integer DEFAULT 0,
  road_type_seq    text,
  waypoints_json   text,
  catalog_pts      text,
  uid              text UNIQUE,
  sha256           text,
  geom             geometry(LineString, 4326),
  ele              double precision[],
  geom_clean       geometry(LineString, 4326),
  ele_clean        double precision[]
);
CREATE INDEX tracks_activity_ix ON tracks (activity);
CREATE INDEX tracks_province_ix ON tracks (province);
CREATE INDEX tracks_ccaa_ix     ON tracks (ccaa);
CREATE INDEX tracks_sierra_ix   ON tracks (sierra);
CREATE INDEX tracks_date_ix     ON tracks (date);
CREATE INDEX tracks_sha256_ix   ON tracks (sha256);
CREATE INDEX tracks_geom_gix    ON tracks USING gist (geom);
CREATE INDEX tracks_name_trgm   ON tracks USING gin (name gin_trgm_ops);

CREATE TABLE config_activities (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text UNIQUE NOT NULL,
  color      text,
  keywords   text,
  sort_order integer DEFAULT 0,
  active     integer DEFAULT 1
);

CREATE TABLE config_sierras (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   text UNIQUE NOT NULL,
  sw_lat double precision,
  sw_lon double precision,
  ne_lat double precision,
  ne_lon double precision,
  active integer DEFAULT 1
);
