-- Fotos de cada track. Los ficheros viven en PHOTOS_DIR (volumen Docker propio);
-- esta tabla es la referencia: qué foto pertenece a qué track y a qué usuario.
CREATE TABLE IF NOT EXISTS track_photos (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  track_id   integer NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
  owner_id   integer REFERENCES users(id) ON DELETE SET NULL,
  filename   text NOT NULL,            -- nombre del fichero en PHOTOS_DIR
  mime       text NOT NULL DEFAULT 'image/jpeg',
  size       integer,
  caption    text,
  position   integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_track_photos_track ON track_photos (track_id);
CREATE INDEX IF NOT EXISTS idx_track_photos_owner ON track_photos (owner_id);
